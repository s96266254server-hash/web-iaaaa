export function getToolById(id: string): AITool | undefined {
  return aiTools.find((t) => t.id === id);
}

export function getToolsByCategory(category: string): AITool[] {
  return aiTools.filter((t) => t.category === category);
}

export function getRelatedTools(toolId: string, limit = 3): AITool[] {
  const tool = getToolById(toolId);
  if (!tool) return [];
  return aiTools
    .filter((t) => t.id !== toolId && t.category === tool.category)
    .slice(0, limit);
}

export function searchTools(query: string): AITool[] {
  const q = query.toLowerCase().trim();
  if (!q) return aiTools;
  return aiTools.filter(
    (t) =>
      t.name.toLowerCase().includes(q) ||
      t.tagline.toLowerCase().includes(q) ||
      t.description.toLowerCase().includes(q) ||
      t.category.toLowerCase().includes(q) ||
      t.features.some((f) => f.toLowerCase().includes(q)) ||
      t.bestFor.toLowerCase().includes(q) ||
      t.pros.some((p) => p.toLowerCase().includes(q)) ||
      t.cons.some((c) => c.toLowerCase().includes(q))
  );
}

